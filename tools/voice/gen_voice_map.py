#!/usr/bin/env python3
"""dos_voice_map.tsv (from align.py) -> core/voice_map.h

Pipeline (game data is not in this repository):
  1. dosmes.py  : Japanese scene scripts from SILK*.DAT (extracted to a folder) -> line list
  2. Korean scene scripts: SAGWA.DAT, directory at the end (bytes XOR 0xAA: len, name, u16 size; files back to back),
     each file decrypted with  plain[i] = ~(enc[i] ^ enc[i-1])  (the first byte is always the u16 code start 0x8E)
  3. align.py   : Windows MES disassembly (voice SYS 7 + TXT) -> Japanese DOS line -> Korean DOS line (anchored on the
     scene commands, then on dialogue/narration order) -> dos_voice_map.tsv  (mes, kr_line, kr_offset, voice)
  4. this script -> core/voice_map.h
"""
import csv, sys
src = sys.argv[1] if len(sys.argv) > 1 else 'dos_voice_map.tsv'
dst = sys.argv[2] if len(sys.argv) > 2 else 'core/voice_map.h'
rows = list(csv.DictReader(open(src), delimiter='\t'))
rows.sort(key=lambda r: (r['mes'], int(r['kr_offset'], 16)))
scenes = sorted({r['mes'][:-4] for r in rows})
seen, lines = set(), []
for r in rows:
    k = (r['mes'], r['kr_offset'])
    if k in seen: continue
    seen.add(k)
    v = r['voice'].upper()[:-4]; assert len(v) < 12
    lines.append('{%d,%s,"%s"},' % (scenes.index(r['mes'][:-4]), r['kr_offset'], v))
out = ['/* generated by tools/voice/gen_voice_map.py: dialogue line start (offset in the Korean scene file) -> voice file in VOICE.ARC */',
       '#ifndef VOICE_MAP_H', '#define VOICE_MAP_H', '#include <stdint.h>',
       'static const char *const VM_SCENES[] = {' + ', '.join('"%s"' % s for s in scenes) + '};',
       '#define VM_NSCENES %d' % len(scenes),
       'typedef struct { uint8_t scene; uint16_t off; char voice[12]; } VoiceLine;',
       '#define VM_NLINES %d' % len(lines),
       'static const VoiceLine VM_LINES[VM_NLINES] = {'] + lines + ['};', '#endif']
open(dst, 'w').write('\n'.join(out) + '\n')
print(len(lines), 'lines,', len(scenes), 'scenes')
