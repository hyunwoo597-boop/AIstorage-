# Bottom-screen toasts for the Y button (tilt parallax on/off). Writes platform/3ds/ui_toast.c (RGBA).
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, S = 220, 34, 4
kr = '/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc'; f = ImageFont.truetype(kr, 16 * S, index=1)
out = open(sys.argv[1], 'w'); out.write('/* generated by tools/mktoast.py: RGBA */\n#include <stdint.h>\nconst int toast_w = %d, toast_h = %d;\n' % (W, H))
for name, text in (('toast_on', '기울기 입체 켜짐'), ('toast_off', '기울기 입체 꺼짐')):
    im = Image.new('RGBA', (W * S, H * S), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    d.rounded_rectangle((0, 0, W * S - 1, H * S - 1), radius=10 * S, fill=(20, 20, 28, 210), outline=(200, 200, 220, 230), width=2 * S)
    d.text((W * S / 2, H * S / 2), text, font=f, fill=(255, 255, 255, 255), anchor='mm')
    im = im.resize((W, H), Image.LANCZOS); im.save('/tmp/' + name + '.png'); px = im.tobytes()
    out.write('const uint8_t %s[] = {\n' % name)
    for i in range(0, len(px), 48): out.write(','.join(str(x) for x in px[i:i + 48]) + ',\n')
    out.write('};\n')
