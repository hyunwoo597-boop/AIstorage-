#!/usr/bin/env python3
"""Regenerates ctr/source/frameshape.h (the shape of the ornamental frame around the game picture).

Input: several decoded screenshots of 640x480 VRAM (PPM) taken in different scenes.  Pixels that are identical in all of them
belong to the frame; the largest connected region of the remaining pixels (picture rows 40..335) is the interior.

  python3 tools/gen_frameshape.py shot1.ppm shot2.ppm ...
(the header that is committed was made from seven different scenes; the frame only changes if the game's graphics change)
"""
import sys
import numpy as np
import scipy.ndimage as ndi
from PIL import Image

shots = [np.array(Image.open(f).convert("RGB")).astype(np.int16) for f in sys.argv[1:]]
same = np.ones(shots[0].shape[:2], bool)
for s in shots[1:]:
    same &= np.abs(s - shots[0]).sum(axis=2) == 0
var = ~same
reg = np.zeros_like(var); reg[40:336, :] = True
var &= reg
v = ndi.binary_fill_holes(ndi.binary_closing(var, structure=np.ones((5, 5)), iterations=2))
lab, n = ndi.label(v)
k = int(np.argmax(ndi.sum(v, lab, range(1, n + 1)))) + 1
inter = ndi.binary_opening(lab == k, structure=np.ones((3, 3)))
L, R, T, B = [], [], [], []
for r in range(40, 336):
    xs = np.where(inter[r])[0]
    L.append(int(xs[0]) if len(xs) else 640); R.append(int(xs[-1]) + 1 if len(xs) else 640)
for c in range(640):
    ys = np.where(inter[40:336, c])[0]
    T.append(int(ys[0]) if len(ys) else 296); B.append(int(ys[-1]) + 1 if len(ys) else 296)

def arr(name, a):
    rows = ["    " + ",".join(str(x) for x in a[i:i + 24]) + "," for i in range(0, len(a), 24)]
    return "static const uint16_t %s[%d] = {\n%s\n};\n" % (name, len(a), "\n".join(rows))

out = ("/* Generated by tools/gen_frameshape.py from game screenshots: the shape of the ornamental frame around the picture (VRAM rows 40..335).\n"
       " * The frame is the same in every scene, so it is described by the inside edge of the frame alone: for every row y the picture interior\n"
       " * starts at x = FR_L[y-40] and ends before x = FR_R[y-40]; for every column x it starts at row FR_T[x] and ends before FR_B[x]\n"
       " * (relative to row 40).  A row or column with FR_L >= FR_R (or FR_T >= FR_B) is frame only.  A pixel of rows 40..335 is interior\n"
       " * if it is inside all four ranges, otherwise it belongs to the frame. */\n#define FR_ROW0 40\n#define FR_ROWS 296\n")
open("ctr/source/frameshape.h", "w").write(out + arr("FR_L", L) + arr("FR_R", R) + arr("FR_T", T) + arr("FR_B", B))
