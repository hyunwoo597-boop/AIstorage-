# Bottom-screen "다음 (터치)" hint with a tapping-hand icon (dialogue screens). Writes platform/3ds/ui_icons.c:
# an 8-bit coverage map (white) of NEXT_W x NEXT_H, drawn at the bottom-right corner.
import sys
from PIL import Image, ImageDraw, ImageFont
out = sys.argv[1]
W, H = 100, 56
im = Image.new('L', (W * 4, H * 4), 0); d = ImageDraw.Draw(im)      # draw 4x, downsample for smooth edges
kr = '/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc'
f1 = ImageFont.truetype(kr, 15 * 4, index=1); f2 = ImageFont.truetype(kr, 13 * 4, index=1)
def ctext(t, f, cx, y): w = d.textlength(t, font=f); d.text((cx - w / 2, y), t, font=f, fill=255)
ctext('다음', f1, 34 * 4, 10 * 4); ctext('(터치)', f2, 34 * 4, 30 * 4)
hand = ImageFont.truetype('/usr/share/fonts/truetype/freefont/FreeSerif.ttf', 44 * 4)
d.text((64 * 4, 9 * 4), '\U0001F446', font=hand, fill=255)
cx, cy = 72 * 4, 15 * 4                                              # tap waves around the fingertip
for r, a in ((8, 255), (13, 200)):
    d.arc((cx - r * 4, cy - r * 4, cx + r * 4, cy + r * 4), 205, 335, fill=a, width=5)
im = im.resize((W, H), Image.LANCZOS); bb = im.getbbox(); im = im.crop((0, 0, W, H))
im.save(out + '.png')
px = im.tobytes()
with open(out, 'w') as f:
    f.write('/* generated by tools/mkicons.py */\n#include <stdint.h>\nconst int next_hint_w = %d, next_hint_h = %d;\nconst uint8_t next_hint[] = {\n' % (W, H))
    for i in range(0, len(px), 40): f.write(','.join(str(x) for x in px[i:i + 40]) + ',\n')
    f.write('};\n')
