#!/usr/bin/env python3
"""Generates ctr/source/kfont.h: the anti-aliased UI font used for the Korean menu text on the 3DS.

Every character that appears in ctr/source/*.c (ASCII 0x20-0x7E plus every non-ASCII character found in the
sources) is rasterised from a TrueType/OpenType font into a small 4-bit alpha bitmap.

  python3 tools/gen_kfont.py [font-file] [pixel-size] [face-index]

The default font is Noto Sans CJK KR Medium (SIL Open Font License 1.1), face 1 of the .ttc collection.
The generated header is committed, so building the app does not need Python or the font.
Re-run this script after adding Korean text to the UI strings.
"""
import glob
import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc"
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 14
INDEX = int(sys.argv[3]) if len(sys.argv) > 3 else 1
GAMMA = 0.80          # < 1 makes thin strokes a little bolder on the dark background

chars = set(chr(c) for c in range(0x20, 0x7F)) | {"?"}
for path in sorted(glob.glob(os.path.join(ROOT, "ctr", "source", "*.c"))):
    with open(path, encoding="utf-8") as f:
        for ch in f.read():
            if ord(ch) >= 0x80:
                chars.add(ch)
chars = sorted(chars, key=ord)

font = ImageFont.truetype(FONT, SIZE, index=INDEX)
print("font:", font.getname(), "size", SIZE, "glyphs", len(chars), file=sys.stderr)

# vertical extent of the whole set relative to the baseline
top, bottom = 0, 0
for ch in chars:
    if ch == " ":
        continue
    l, t, r, b = font.getbbox(ch, anchor="ls")
    top, bottom = min(top, t), max(bottom, b)
height = bottom - top
base = -top


def advance(ch):
    if ord(ch) >= 0x1100:                   # hangul, CJK, full-width punctuation: one em
        return SIZE
    return max(2, int(round(font.getlength(ch))))


cp_list, adv_list, off_list, data = [], [], [], bytearray()
for ch in chars:
    adv = advance(ch)
    img = Image.new("L", (adv + 4, height), 0)
    ImageDraw.Draw(img).text((0, base), ch, font=font, fill=255, anchor="ls")
    img = img.crop((0, 0, adv, height))
    px = list(img.tobytes())
    q = [min(15, int(round(15 * math.pow(v / 255.0, GAMMA)))) for v in px]
    if len(q) % 2:
        q.append(0)
    off_list.append(len(data))
    for i in range(0, len(q), 2):
        data.append((q[i] << 4) | q[i + 1])
    cp_list.append(ord(ch))
    adv_list.append(adv)

assert len(data) < 65536

out = []
out.append("/* Generated by tools/gen_kfont.py - do not edit.  UI font: %s %s, %d px, %d glyphs.\n"
           " * Source font: Noto Sans CJK KR (SIL Open Font License 1.1).  Each glyph is adv x KF_H pixels of 4-bit alpha, two per byte. */" %
           (font.getname()[0], font.getname()[1], SIZE, len(chars)))
out.append("#include <stdint.h>")
out.append("#define KF_H %d" % height)
out.append("#define KF_BASE %d" % base)
out.append("#define KF_N %d" % len(chars))


def arr(name, typ, vals, per=12):
    out.append("static const %s %s[] = {" % (typ, name))
    for i in range(0, len(vals), per):
        out.append("  " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")


arr("kf_cp", "uint32_t", cp_list, 10)
arr("kf_adv", "uint8_t", adv_list, 20)
arr("kf_off", "uint16_t", off_list, 12)
arr("kf_data", "uint8_t", list(data), 24)
dst = os.path.join(ROOT, "ctr", "source", "kfont.h")
with open(dst, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote", dst, "(%d bytes of bitmap, cell height %d, baseline %d)" % (len(data), height, base), file=sys.stderr)
