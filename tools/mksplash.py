# Start-up splash for the 3DS build: a stereo pair from an MPO (top screen, 400x240 per eye) + a bottom-screen prompt.
# Output: platform/3ds/splash_data.c with an LZSS block (engine LZSS) of RGB565 pixels, row-major:
#   left 400x240, right 400x240, bottom 320x240.
# usage: mksplash.py picture.mpo lzss_enc_binary out.c
import sys, struct, subprocess, tempfile, os
from PIL import Image, ImageDraw, ImageFont
import numpy as np
mpo, lz, out = sys.argv[1:4]
im = Image.open(mpo); eyes = []
for i in range(2):
    im.seek(i); f = im.convert('RGB'); a = np.asarray(f).astype(int).sum(2)
    rows = np.where(a.mean(1) > 20)[0]; f = f.crop((0, rows.min(), f.width, rows.max() + 1))     # drop letterbox bars
    h = round(f.height * 400 / f.width); f = f.resize((400, h), Image.LANCZOS)
    top = (h - 240) // 2; eyes.append(f.crop((0, top, 400, top + 240)) if h >= 240 else f)
# bottom screen prompt
KR = '/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'
b = Image.new('RGB', (320, 240), (8, 10, 28)); d = ImageDraw.Draw(b)
for y in range(240):                                    # soft navy gradient
    c = int(8 + 22 * (y / 239)); d.line([(0, y), (319, y)], fill=(c // 2, c // 2, c + 14))
big = ImageFont.truetype(KR, 30, index=1); small = ImageFont.truetype(KR, 17, index=1)
def centre(text, font, y, fill):
    w = d.textlength(text, font=font); d.text(((320 - w) / 2, y), text, font=font, fill=fill)
centre('A 버튼 시작', big, 93, (255, 255, 255))
centre('(화면을 터치해서 시작)', small, 146, (200, 205, 230))
d.line([(40, 80), (280, 80)], fill=(239, 0, 95), width=1); d.line([(40, 180), (280, 180)], fill=(239, 0, 95), width=1)
def rgb565(img):
    a = np.asarray(img.convert('RGB')).astype(np.uint16)
    return ((a[..., 0] >> 3) << 11 | (a[..., 1] >> 2) << 5 | (a[..., 2] >> 3)).astype('<u2').tobytes()
raw = rgb565(eyes[0]) + rgb565(eyes[1]) + rgb565(b)
with tempfile.TemporaryDirectory() as t:
    p = os.path.join(t, 'r'); open(p, 'wb').write(raw); subprocess.run([lz, p, p + '.lz'], check=True, capture_output=True); comp = open(p + '.lz', 'rb').read()
with open(out, 'w') as f:
    f.write('/* generated by tools/mksplash.py: LZSS of RGB565 left 400x240, right 400x240, bottom 320x240 */\n#include <stdint.h>\n#include <stddef.h>\n')
    f.write('const size_t splash_raw_size = %d;\nconst size_t splash_lz_size = %d;\nconst uint8_t splash_lz[] = {\n' % (len(raw), len(comp)))
    for i in range(0, len(comp), 32): f.write(','.join(str(x) for x in comp[i:i + 32]) + ',\n')
    f.write('};\n')
Image.fromarray(np.hstack([np.asarray(eyes[0]), np.asarray(eyes[1])])).save(out + '.top.png'); b.save(out + '.bottom.png')
print(len(raw), '->', len(comp))
