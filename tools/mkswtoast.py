# Switch "-" button labels (DOS/Windows picture switch). Writes platform/switch/toast_kr.c: 8-bit alpha, 32 px high.
import sys
from PIL import Image, ImageDraw, ImageFont
# usage: mkswtoast.py <out.c> [height font-size prefix]   (3DS: 24 16 dostoast)
H = int(sys.argv[2]) if len(sys.argv) > 2 else 32
FS = int(sys.argv[3]) if len(sys.argv) > 3 else 22
PRE = sys.argv[4] if len(sys.argv) > 4 else 'swtoast'
f = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', FS, index=1)
labels = ('PC98 그래픽', 'HD 리마스터 그래픽', '도스판 파일 없음 (SILK0-4.DAT)')
out = open(sys.argv[1], 'w'); out.write('/* generated by tools/mkswtoast.py: 8-bit alpha, %d px high */\n#include <stdint.h>\n' % H)
ws = []
for n, t in enumerate(labels):
    w = int(ImageDraw.Draw(Image.new('L', (1, 1))).textlength(t, font=f)) + 4; ws.append(w)
    im = Image.new('L', (w, H), 0); ImageDraw.Draw(im).text((2, H // 2), t, font=f, fill=255, anchor='lm'); px = im.tobytes()
    out.write('static const uint8_t %s_lab%d[] = {\n' % (PRE, n))
    for i in range(0, len(px), 64): out.write(','.join(str(x) for x in px[i:i + 64]) + ',\n')
    out.write('};\n')
out.write('const int {0}_h = {1};\nconst int {0}_w[3] = {{ {2} }};\nconst uint8_t *const {0}_px[3] = {{ {0}_lab0, {0}_lab1, {0}_lab2 }};\n'.format(PRE, H, ', '.join(map(str, ws))))
