#!/usr/bin/env python3
"""Generates ctr/source/splash.h: the stereoscopic title picture shown on the top screen when the app starts (waits for A / a touch).

  python3 tools/gen_splash.py [left.png right.png]      (default: tools/splash_L.png and tools/splash_R.png, 400x240 each)

The two pictures are the left-eye and right-eye images of a 3D pair (they are resized to 400x240 if they are not already).  They are converted
to RGB565 with an ordered (Bayer 8x8) dither - the dark sky would band badly otherwise - and stored in the framebuffer's own layout:
column-major, 240 pixels per column, y flipped, i.e. SPLASH_L[x * 240 + (239 - y)].  The dither pattern depends only on the screen position,
so the same pixel gets the same rounding in both eyes (an error-diffusion dither would put different noise into each eye).  The generated
header is committed, so building the app does not need Python.
"""
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_L = sys.argv[1] if len(sys.argv) > 2 else os.path.join(ROOT, "tools", "splash_L.png")
SRC_R = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "tools", "splash_R.png")
W, H = 400, 240

BAYER = np.array([[0, 32, 8, 40, 2, 34, 10, 42], [48, 16, 56, 24, 50, 18, 58, 26], [12, 44, 4, 36, 14, 46, 6, 38], [60, 28, 52, 20, 62, 30, 54, 22],
                  [3, 35, 11, 43, 1, 33, 9, 41], [51, 19, 59, 27, 49, 17, 57, 25], [15, 47, 7, 39, 13, 45, 5, 37], [63, 31, 55, 23, 61, 29, 53, 21]], dtype=np.float64)
THR = (BAYER + 0.5) / 64.0                       # thresholds in (0, 1)


def to565(path):
    im = Image.open(path).convert("RGB")
    if im.size != (W, H):
        im = im.resize((W, H), Image.LANCZOS)
    a = np.asarray(im, dtype=np.float64)
    thr = np.tile(THR, (H // 8 + 1, W // 8 + 1))[:H, :W]
    out = np.zeros((H, W), dtype=np.uint16)
    chans = []
    for c, lv in enumerate((31.0, 63.0, 31.0)):
        v = a[:, :, c] / 255.0 * lv
        q = np.floor(v + thr)                    # round up with probability = fractional part, decided by the fixed pattern
        chans.append(np.clip(q, 0, lv).astype(np.uint16))
    out = (chans[0] << 11) | (chans[1] << 5) | chans[2]
    return out


def emit(name, out):
    vals = [int(out[y, x]) for x in range(W) for y in range(H - 1, -1, -1)]      # index x*240 + (239-y)  ->  y runs from 239 down to 0 inside each column
    lines = ["static const uint16_t %s[%d * %d] = {" % (name, W, H)]
    for i in range(0, len(vals), 20):
        lines.append("  " + ",".join("0x%04X" % v for v in vals[i:i + 20]) + ",")
    lines.append("};")
    return lines, vals


def preview(out, path):
    rgb = np.zeros((H, W, 3), dtype=np.uint8)
    rgb[:, :, 0] = ((out >> 11) & 31) * 255 // 31
    rgb[:, :, 1] = ((out >> 5) & 63) * 255 // 63
    rgb[:, :, 2] = (out & 31) * 255 // 31
    Image.fromarray(rgb).save(path)


L, R = to565(SRC_L), to565(SRC_R)
lines = ["/* Generated by tools/gen_splash.py - do not edit.  Stereo title picture, two 400x240 RGB565 images (left eye / right eye), framebuffer layout: SPLASH_L[x * 240 + (239 - y)]. */",
         "#include <stdint.h>", "#define SPLASH_W 400", "#define SPLASH_H 240"]
for name, out in (("SPLASH_L", L), ("SPLASH_R", R)):
    ls, vals = emit(name, out)
    lines += ls
dst = os.path.join(ROOT, "ctr", "source", "splash.h")
with open(dst, "w") as f:
    f.write("\n".join(lines) + "\n")
preview(L, "/tmp/splash_prev_L.png")
preview(R, "/tmp/splash_prev_R.png")
print("wrote", dst, file=sys.stderr)
