#!/usr/bin/env python3
"""Generates ctr/source/splash.h: the title picture shown on the top screen when the app starts (waits for the A button).

  python3 tools/gen_splash.py [source.png]      (default: tools/splash_src.png, a square picture)

The picture is scaled to 240x240 (it is shown centred on the 400x240 top screen), converted to RGB565 with Floyd-Steinberg dithering
(the dark sky would band badly otherwise) and stored in the framebuffer's own layout: column-major, 240 pixels per column, y flipped,
i.e. SPLASH[x * 240 + (239 - y)].  The generated header is committed, so building the app does not need Python.
"""
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "splash_src.png")
N = 240

im = Image.open(SRC).convert("RGB")
im = im.resize((N, N), Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=0.8, percent=40, threshold=2))
a = np.asarray(im, dtype=np.float64)

out = np.zeros((N, N), dtype=np.uint16)
lv = np.array([31.0, 63.0, 31.0])
for y in range(N):
    for x in range(N):
        old = a[y, x]
        q = np.clip(np.round(old / 255.0 * lv), 0, lv)
        new = q / lv * 255.0
        err = old - new
        if x + 1 < N: a[y, x + 1] += err * 7 / 16
        if y + 1 < N:
            if x > 0: a[y + 1, x - 1] += err * 3 / 16
            a[y + 1, x] += err * 5 / 16
            if x + 1 < N: a[y + 1, x + 1] += err * 1 / 16
        out[y, x] = (int(q[0]) << 11) | (int(q[1]) << 5) | int(q[2])

lines = ["/* Generated by tools/gen_splash.py - do not edit.  Title picture, 240x240 RGB565, framebuffer layout: SPLASH[x * 240 + (239 - y)]. */",
         "#include <stdint.h>", "#define SPLASH_W 240", "#define SPLASH_H 240", "static const uint16_t SPLASH[240 * 240] = {"]
vals = [int(out[y, x]) for x in range(N) for y in range(N - 1, -1, -1)]      # index x*240 + (239-y)  ->  y runs from 239 down to 0 inside each column
for i in range(0, len(vals), 16):
    lines.append("  " + ",".join("0x%04X" % v for v in vals[i:i + 16]) + ",")
lines.append("};")
dst = os.path.join(ROOT, "ctr", "source", "splash.h")
with open(dst, "w") as f:
    f.write("\n".join(lines) + "\n")
Image.fromarray(np.array([[(((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31) for v in [int(out[y, x]) for x in range(N)]] for y in range(N)], dtype=np.uint8)).save("/tmp/splash_preview.png")
print("wrote", dst, len(vals), "pixels", file=sys.stderr)
