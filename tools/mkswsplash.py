# Switch start-up splash + icon from one 4:3 picture (assets/splash/switch_title.png).
# Writes platform/switch/splash_sw.c: LZSS (engine LZSS, tools/lzss_enc.c) of RGB24 960x720, and an RGBA prompt
# ("A 버튼으로 시작") drawn over it; and assets/icon_switch.jpg (256x256, the left square with the title).
# usage: mkswsplash.py picture.png lzss_enc_binary out.c icon.jpg
import sys, subprocess, tempfile, os
from PIL import Image, ImageDraw, ImageFont, ImageFilter
pic, lz, out, icon = sys.argv[1:5]
im = Image.open(pic).convert('RGB')
main = im.resize((960, 720), Image.LANCZOS)
s = min(im.width, im.height); im.crop((0, 0, s, s)).resize((256, 256), Image.LANCZOS).save(icon, quality=92)
KR = '/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc'
f = ImageFont.truetype(KR, 40, index=1); text = 'A 버튼으로 시작'
w = int(ImageDraw.Draw(Image.new('L', (1, 1))).textlength(text, font=f)) + 40; h = 72
mask = Image.new('L', (w, h)); ImageDraw.Draw(mask).text((w // 2, h // 2), text, font=f, fill=255, anchor='mm')
glow = mask.filter(ImageFilter.MaxFilter(7)).filter(ImageFilter.GaussianBlur(3))
p = Image.new('RGBA', (w, h), (10, 20, 60, 0)); p.putalpha(glow.point(lambda v: min(255, v * 2)))
fg = Image.new('RGBA', (w, h), (255, 255, 255, 255)); fg.putalpha(mask); p = Image.alpha_composite(p, fg)
raw = main.tobytes()
with tempfile.TemporaryDirectory() as t:
    q = os.path.join(t, 'r'); open(q, 'wb').write(raw); subprocess.run([lz, q, q + '.lz'], check=True, capture_output=True); comp = open(q + '.lz', 'rb').read()
with open(out, 'w') as o:
    o.write('/* generated by tools/mkswsplash.py: LZSS of RGB24 960x720 (the title picture) + RGBA prompt */\n#include <stdint.h>\n#include <stddef.h>\n')
    o.write('const size_t swsplash_raw_size = %d, swsplash_lz_size = %d;\nconst uint8_t swsplash_lz[] = {\n' % (len(raw), len(comp)))
    for i in range(0, len(comp), 40): o.write(','.join(str(x) for x in comp[i:i + 40]) + ',\n')
    o.write('};\nconst int swprompt_w = %d, swprompt_h = %d;\nconst uint8_t swprompt_rgba[] = {\n' % (w, h))
    pb = p.tobytes()
    for i in range(0, len(pb), 64): o.write(','.join(str(x) for x in pb[i:i + 64]) + ',\n')
    o.write('};\n')
prev = Image.new('RGB', (1280, 720)); bg = im.resize((1280, 962), Image.LANCZOS).crop((0, 121, 1280, 841)).filter(ImageFilter.GaussianBlur(12))
prev.paste(Image.eval(bg, lambda v: v * 2 // 5)); prev.paste(main, (160, 0)); prev.paste(p, ((1280 - w) // 2, 720 - h - 24), p); prev.save(out + '.png')
print(len(raw), '->', len(comp), 'icon', os.path.getsize(icon))
